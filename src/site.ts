// UTM-разметка ссылок воронки: видно, с какой страницы ушёл человек.
// medium = место клика (cta_header / cta_footer / cta_block / cta_inline / cta_hero),
// content = страница (слаг статьи, home, guides)
export function funnelUrl(base: string, campaign: string, medium: string, pathname: string): string {
  const page = pathname.replace(/^\/+|\/+$/g, '').replace(/\//g, '-') || 'home';
  const sep = base.includes('?') ? '&' : '?';
  return `${base}${sep}utm_source=blog&utm_medium=${medium}&utm_campaign=${campaign}&utm_content=${page}`;
}
